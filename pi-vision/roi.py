"""
ซูมเข้าที่ใบหน้า แล้วอ่าน landmark จากภาพครอปแทนภาพเต็ม

ทำไมต้องมี: `FaceLandmarker` ย่อภาพที่รับเข้าไปให้เหลือขนาดของโมเดลเสมอ คนที่อยู่ไกล
จึงเหลือใบหน้าไม่กี่พิกเซลก่อนโมเดลจะได้เห็นด้วยซ้ำ · การครอปเฉพาะบริเวณใบหน้าแล้ว
ขยายก่อนส่งเข้าโมเดล ทำให้ใบหน้าที่อยู่ไกลมีรายละเอียดเท่ากับใบหน้าที่อยู่ใกล้กล้อง
ผลคือได้ landmark ที่ใช้งานได้จริง → วัดตาได้ · เทียบกับรูปในแกลเลอรีได้ · ไกลขึ้นมาก

──────────────────────────────────────────────────────────────────────────────
⚠️ **กรอบครอปต้องมีอัตราส่วนเท่ากับเฟรมเต็มเสมอ** — ข้อนี้ไม่ใช่รายละเอียดความสวยงาม

`landmarks.face_signature()` กับ `head_pose()` วัดระยะจากพิกัด normalized ซึ่งแกน x
หารด้วยความกว้างภาพ และแกน y หารด้วยความสูงภาพ · ป้อนภาพที่อัตราส่วนต่างจากเดิม
เข้าไปเมื่อไร ทุกค่าในลายเซ็น 8 ตัวจะเลื่อนไปทั้งชุด แกลเลอรีจะจำคนไม่ได้ และ
ท่านิ่งที่อ่านจากรูปจะเพี้ยน · และมันจะเพี้ยนอย่างเงียบ ๆ ไม่มี error ให้เห็น
มีแค่ "ระบบจำคนแย่ลงเฉย ๆ" ซึ่งหาสาเหตุยากมาก

เมื่อล็อกอัตราส่วนไว้ การครอปกลายเป็นแค่ **เลื่อนกับย่อ/ขยายเท่ากันทั้งสองแกน**
ในพิกัด normalized (ดู `remap`) อัตราส่วนของระยะทุกคู่จึงไม่เปลี่ยนเลย
`test_roi.py` ยึดข้อนี้ไว้ด้วยเทสที่เทียบลายเซ็นก่อน-หลังครอปให้ตรงกันถึง 1e-9
──────────────────────────────────────────────────────────────────────────────
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Point:
    """เลียนแบบ NormalizedLandmark ของ mediapipe เท่าที่โค้ดอื่นใช้ (x · y · z)

    ต้องสร้างของเราเองเพราะ landmark ที่ mediapipe คืนมาแก้ค่าไม่ได้ และเราต้อง
    แปลงพิกัดจาก "ในภาพครอป" เป็น "ในเฟรมเต็ม" ก่อนส่งต่อให้ส่วนที่เหลือของระบบ
    """

    x: float
    y: float
    z: float = 0.0


def crop_rect(box, frame_w: int, frame_h: int, margin: float,
              aspect: float | None = None) -> tuple[int, int, int, int]:
    """
    กรอบครอปรอบใบหน้า — คืนพิกัดพิกเซล `(x1, y1, x2, y2)`

    `box` คือกรอบใบหน้าแบบ normalized · `margin` คือส่วนเผื่อรอบ ๆ (0.6 = ขยาย 60%)

    `aspect` = อัตราส่วนที่ต้องการ · ไม่ระบุ = ใช้อัตราส่วนของภาพที่ส่งเข้ามา
    ระบุเมื่อภาพต้นทางมีอัตราส่วนต่างจากปลายทาง — เช่นตอนอ่าน**รูปลงทะเบียน**
    ซึ่งเป็นรูปจากมือถือ (แนวตั้ง) แต่ต้องให้ลายเซ็นเทียบได้กับภาพจากกล้อง (4:3)
    ต้องเผื่อพอสมควรเพราะตัวตรวจใบหน้าใน FaceLandmarker ต้องการเห็นบริบทรอบหน้า
    ไม่ใช่แค่ใบหน้าที่ถูกตัดชิดขอบ

    ขั้นตอน: ขยายตามส่วนเผื่อ → **บังคับอัตราส่วนให้เท่าเฟรม** → ย่อลงถ้าใหญ่เกินเฟรม
    → เลื่อนเข้ามาถ้าล้นขอบ · การเลื่อน (ไม่ใช่การตัด) คือสิ่งที่รักษาอัตราส่วนไว้ได้
    เมื่อใบหน้าอยู่ชิดขอบเฟรม ซึ่งเป็นตอนที่โค้ดแบบตัดขอบจะทำอัตราส่วนพัง
    """
    x1, y1, x2, y2 = box
    cx = (x1 + x2) / 2.0 * frame_w
    cy = (y1 + y2) / 2.0 * frame_h
    w = max(x2 - x1, 0.0) * frame_w * (1.0 + 2.0 * margin)
    h = max(y2 - y1, 0.0) * frame_h * (1.0 + 2.0 * margin)

    # บังคับอัตราส่วนให้ตรงกับเฟรม โดย**ขยายด้านที่สั้น** ไม่ใช่หดด้านที่ยาว
    # (การหดจะตัดส่วนของใบหน้าออกไป ซึ่งทำให้ landmark หายและลายเซ็นเพี้ยน)
    aspect = aspect or frame_w / max(frame_h, 1)
    if w / max(h, 1e-6) > aspect:
        h = w / aspect
    else:
        w = h * aspect

    # ใหญ่เกินเฟรม = ย่อลงมาทั้งคู่เท่า ๆ กัน เพื่อไม่ให้อัตราส่วนเสีย
    if w > frame_w or h > frame_h:
        shrink = min(frame_w / max(w, 1e-6), frame_h / max(h, 1e-6))
        w, h = w * shrink, h * shrink

    # เลื่อนกรอบเข้ามาให้อยู่ในเฟรม แทนการตัดขอบทิ้ง
    cx = min(max(cx, w / 2.0), frame_w - w / 2.0)
    cy = min(max(cy, h / 2.0), frame_h - h / 2.0)

    rx1 = int(round(cx - w / 2.0))
    ry1 = int(round(cy - h / 2.0))
    return rx1, ry1, rx1 + int(round(w)), ry1 + int(round(h))


def remap(landmarks, rect, frame_w: int, frame_h: int) -> list[Point]:
    """
    แปลง landmark ที่อ่านจากภาพครอป ให้เป็นพิกัดของเฟรมเต็ม

    เมื่อกรอบครอปมีอัตราส่วนเท่าเฟรม (ดู `crop_rect`) การแปลงนี้คือ
    **เลื่อน + คูณด้วยค่าเดียวกันทั้งสองแกน** ในพิกัด normalized:

        x_เฟรม = rx1/frame_w + x_ครอป × s        โดย s = (rx2-rx1)/frame_w
        y_เฟรม = ry1/frame_h + y_ครอป × s        และ s = (ry2-ry1)/frame_h ค่าเดียวกัน

    อัตราส่วนของระยะทุกคู่จึงเท่าเดิมเป๊ะ — ซึ่งเป็นเหตุผลทั้งหมดที่ต้องล็อกอัตราส่วน

    `z` ของ mediapipe คิดสเกลตามความกว้างภาพ จึงคูณด้วย s เหมือนกัน
    """
    rx1, ry1, rx2, ry2 = rect
    sx = (rx2 - rx1) / max(frame_w, 1)
    sy = (ry2 - ry1) / max(frame_h, 1)
    ox = rx1 / max(frame_w, 1)
    oy = ry1 / max(frame_h, 1)
    return [
        Point(x=ox + p.x * sx, y=oy + p.y * sy, z=getattr(p, "z", 0.0) * sx)
        for p in landmarks
    ]


def blend_rect(old, new, alpha: float):
    """
    เกลี่ยกรอบครอปกับกรอบของเฟรมก่อน — กันภาพซูมกระตุกและกัน landmark สั่น

    กรอบที่ขยับทุกเฟรมทำให้ภาพที่ป้อนเข้าโมเดลเปลี่ยนมุมตลอด landmark ที่ได้จึงสั่น
    ตามไปด้วย แม้คนจะนั่งนิ่ง · ยิ่ง alpha สูงยิ่งนิ่งแต่ตามคนที่เดินเร็วได้ช้าลง
    """
    if old is None:
        return new
    return tuple(int(round(o * alpha + n * (1.0 - alpha))) for o, n in zip(old, new))


NEVER = float("-inf")


def pick(items, budget: int, last_at) -> list:
    """
    เลือกว่าเฟรมนี้จะซูมเข้าที่ใคร — คืนรายการยาวไม่เกิน `budget`

    ซูมทุกคนทุกเฟรมแพงเกินไปบน Pi (คือ inference หนึ่งครั้งต่อคนต่อเฟรม) แต่ก็ไม่
    จำเป็นต้องทำ เพราะสิ่งที่การซูมให้มา — ลายเซ็นสำหรับเทียบชื่อ และค่าจากดวงตา —
    เปลี่ยนช้ากว่าเฟรมมาก

    `last_at(item)` คืนเวลาที่ซูมครั้งล่าสุด หรือ `NEVER` ถ้ายังไม่เคย · เรียงตามค่านั้น
    จึงเป็นการวนให้ทั่วโดยธรรมชาติ ไม่มีใครถูกทิ้งแม้มีคนมากกว่าโควตาหลายเท่า
    และคนที่ยังไม่เคยถูกซูมเลยได้ก่อนเสมอ

    รับ `items` เป็นอะไรก็ได้ (track หรือกรอบจากตัวตรวจ) เพราะคนที่อยู่ไกลจนยังไม่มี
    track เป็นกลุ่มที่ต้องการการซูมมากที่สุด — ผูกไว้กับ track อย่างเดียวไม่ได้
    """
    if budget <= 0:
        return []
    return sorted(items, key=last_at)[:budget]

"""
โหมดการทำงานของ pi-vision

โหมดไม่ใช่ไปป์ไลน์คนละเส้น — เป็นแค่ **นโยบาย** ที่ทับค่าตั้งบางตัวของไปป์ไลน์เดิม
ทำแบบนี้เพื่อไม่ให้มีโค้ดวิเคราะห์ใบหน้าสองชุดที่ต้องคอยแก้ให้ตรงกัน

ตอนนี้มีสี่โหมด — สามโหมดอยู่ในเมนู อีกหนึ่งเรียกผ่านค่าตั้งเท่านั้น

  activity — เห็นคนได้ไกลด้วยโมเดล full-range · ซูมเข้าใบหน้าเพื่อคง id ตอนคนเดิน
             · บอกกิจกรรม (ยืน/นั่ง/เดิน/วิ่ง/กวาดสายตา)          ← เมนูข้อ 1
  person   — ติดตามทีละคนพร้อม re-ID (โหมดเดิม)
  known    — รู้จักเฉพาะคนที่มีรูปใน faces/ · ไม่จำใครนอกเหนือจากนั้น
  room     — วัดภาพรวมของห้อง ไม่แยกรายบุคคล ไม่เก็บลายเซ็นโครงหน้า
             **ไม่อยู่ในเมนูแล้ว** — ตั้ง VISION_MODE=room หรือ --mode room เพื่อใช้

`ORDER` คือสิ่งที่เมนูแสดง · `MODES` คือทุกโหมดที่เรียกใช้ได้ · โหมดที่หลุดจาก ORDER
ยังทำงานได้ครบและยังถูกเทสอยู่ทุกข้อ แค่ไม่ถูกเสนอให้คนที่เพิ่งเปิดโปรแกรมครั้งแรก
— การเอาออกจากเมนูกับการลบโค้ดทิ้งเป็นคนละเรื่องกัน และอย่างหลังจะพา to_room_row()
occupancy() attention_ratio() กับ test_room_smoke.py หายไปด้วยทั้งที่ยังทำงานได้ดี

ถ้าจะเพิ่มโหมดใหม่ ให้เพิ่ม Mode เข้า MODES แล้วโมดูลอื่นจะรับไปเองทั้งหมด
"""

from __future__ import annotations

from dataclasses import dataclass

ROOM = "room"
PERSON = "person"
KNOWN = "known"
ACTIVITY = "activity"


@dataclass(frozen=True)
class Mode:
    """นโยบายหนึ่งชุด — อ่านอย่างเดียว ไม่มีใครแก้ระหว่างรันได้"""

    key: str
    label: str
    summary: str                 # อธิบายสั้น ๆ ตอนถามผู้ใช้ให้เลือก
    signatures: bool             # คำนวณลายเซ็นโครงหน้าไหม (ข้อมูลชีวมิติแบบอ่อน)
    reid: bool                   # คืน id เดิมเมื่อคนออกไปแล้วกลับมาไหม
    report_person: bool          # ใส่คอลัมน์ person ลงตาราง focus ไหม
    per_person_hud: bool         # HUD แสดงทีละคน หรือแสดงภาพรวมห้อง
    eyes: bool                   # วัดการกะพริบตา · EAR · ความง่วง ไหม
    gallery: bool = False        # อ่านรูปใน faces/ มาเทียบชื่อไหม
    known_only: bool = False     # รายงานเฉพาะคนที่จับคู่รูปได้ · คนอื่นไม่มีแถวของตัวเอง

    # ── ความสามารถของโหมดติดตามกิจกรรม ────────────────────────
    # แยกเป็นธงทีละอย่าง **ไม่ใช่ให้โมดูลอื่นเช็คชื่อโหมด** — โมดูลอื่นจึงไม่ต้องรู้จัก
    # ชื่อโหมดเลย และวันหนึ่งถ้าอยากเปิดทีละอย่างให้โหมดอื่นก็ทำได้โดยไม่ต้องแก้ที่อื่น
    # ทั้งสี่ค่าเป็น False ในโหมดเดิมทั้งสาม = โหมดเดิมทำงานเหมือนเดิมทุกอย่าง
    full_range: bool = False     # ใช้โมเดลตรวจใบหน้าระยะไกล (full-range) นำหน้าไปป์ไลน์
    roi_zoom: bool = False       # ครอปซูมเข้าที่ใบหน้าแล้วอ่าน landmark ซ้ำจากภาพครอป
    activity: bool = False       # บอกว่ากำลังยืนขึ้น/นั่งลง/เดิน/วิ่ง/กวาดสายตา
    zoom_panel: bool = False     # แผงภาพซูมมุมจอ + การ์ดข้อมูลของคนที่กำลังขยับ

    def apply_to_tracker(self, tracker_cfg: dict) -> dict:
        """คืน tracker config ชุดใหม่ที่ผ่านนโยบายของโหมดนี้แล้ว (ไม่แก้ของเดิม)"""
        cfg = dict(tracker_cfg)
        if not self.reid:
            cfg["reid_enabled"] = False
        # การ**เฉลี่ยลายเซ็นข้ามเฟรม** กับการ**จำคนที่ออกจากเฟรม** เป็นสองเรื่อง
        # โหมด known ต้องมีอย่างแรก (ไม่งั้นไม่มีลายเซ็นที่นิ่งพอไปเทียบกับรูป)
        # แต่ต้องไม่มีอย่างหลัง (ไม่เก็บ pool ของคนที่ไม่มีรูป) — ถ้าผูกสองเรื่องนี้ไว้
        # ด้วยธงเดียว โหมด known จะเงียบสนิทโดยไม่มีใครรู้ว่าเพราะอะไร
        cfg["learn_signatures"] = self.reid or self.gallery
        if self.roi_zoom:
            # เกณฑ์ "ใบหน้าต้องใหญ่เท่านี้ถึงเชื่อลายเซ็นได้" ตั้งไว้สำหรับ landmark
            # ที่อ่านจาก**ภาพเต็ม** ซึ่งใบหน้าเล็ก = landmark หยาบ = ลายเซ็นมั่ว
            # โหมดที่ซูมอ่าน landmark จากภาพครอปที่ขยายแล้ว ใบหน้าที่กินพื้นที่ 3%
            # ของเฟรมจึงให้ landmark ละเอียดพอ ๆ กับใบหน้าที่กิน 12% ในโหมดอื่น
            # ถ้าไม่ลดเกณฑ์ตรงนี้ การซูมจะไม่ให้ประโยชน์อะไรเลย — ได้ landmark ดี ๆ
            # มาแล้วถูกทิ้งที่ประตูบานเดิม
            cfg["reid_min_size"] = min(cfg["reid_min_size"], ZOOMED_MIN_SIZE)
        return cfg

    def apply_to_faces(self, faces_cfg: dict) -> dict:
        """คืน faces config ที่ผ่านนโยบายของโหมดนี้แล้ว — เหตุผลเดียวกับ apply_to_tracker"""
        cfg = dict(faces_cfg)
        if self.roi_zoom:
            cfg["min_size"] = min(cfg["min_size"], ZOOMED_MIN_SIZE)
        return cfg


# ใบหน้าต้องกินพื้นที่อย่างน้อยเท่านี้ของเฟรม ถึงจะเชื่อลายเซ็นได้ **เมื่อซูมแล้ว**
# 0.03 ของเฟรมกว้าง 640 = กรอบราว 19 px ซึ่งพอให้ครอปแล้วขยายเป็น 256 px ได้ผลจริง
# ต่ำกว่านี้คือขยายสัญญาณรบกวน ไม่ใช่ขยายรายละเอียด
ZOOMED_MIN_SIZE = 0.03



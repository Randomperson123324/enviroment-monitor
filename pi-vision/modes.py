# ทุกโหมดที่เรียกใช้ได้ — รวมโหมดที่ไม่อยู่ในเมนู
# ใช้กับ --mode เพื่อให้ --mode room ยังใช้ได้ (ถ้าผูกกับ ORDER จะหายไปเงียบ ๆ)
ALL = tuple(MODES)

# ลำดับที่แสดงในเมนู — known อยู่ท้ายเพราะต้องเตรียมรูปก่อนจึงจะใช้ได้
# ห้องรวมไม่อยู่ในลิสต์นี้แล้ว แต่ยังอยู่ใน MODES (ดูหัวไฟล์)
ORDER = (ACTIVITY, PERSON, KNOWN)

# ค่าเริ่มต้นของ**เมนู** — กด Enter เฉย ๆ ได้ข้อ 1
DEFAULT = ACTIVITY

# ค่าเริ่มต้นเมื่อ**ไม่มีใครให้ถาม** (cron · systemd · ท่อ) — คนละค่ากับข้างบนโดยตั้งใจ
#
# เดิมสองอย่างนี้เป็นค่าเดียวกันได้เพราะข้อ 1 คือห้องรวมซึ่งไม่ระบุตัวบุคคลอยู่แล้ว
# พอข้อ 1 กลายเป็นโหมดที่จำหน้า ติดชื่อจริง และวาดภาพใบหน้าขยายขึ้นจอ การใช้ค่าเดียวกัน
# แปลว่าเครื่องที่บูตขึ้นมาเองโดยไม่มีใครอยู่ตรงนั้น จะเริ่มทำสิ่งเหล่านั้นทันทีโดยไม่มีใครเลือก
# — จึงให้ทางที่ไม่มีคนตัดสินใจตกไปที่โหมดที่ไม่ผูกกับตัวบุคคลตามเดิม
# อยากให้เครื่องขึ้นมาเป็นโหมดติดตามกิจกรรมเสมอ: ตั้ง VISION_MODE=activity ใน .env
# (ระบุไว้ชัด ๆ ดีกว่าเปลี่ยนค่านี้ เพราะค่านี้คือทางที่ "ไม่มีใครเลือก")
HEADLESS_DEFAULT = ROOM


def get(key: str | None) -> Mode:
    """แปลงชื่อโหมดเป็น Mode — ชื่อที่ไม่รู้จักถือเป็นความผิดพลาดของค่าตั้ง ไม่เดาให้"""
    if key is None:
        return MODES[DEFAULT]
    normalized = key.strip().lower()
    if normalized not in MODES:
        # ลิสต์จาก ALL ไม่ใช่ ORDER — ไม่งั้นคนที่พิมพ์ผิดจะไม่มีทางรู้ว่า room ยังมีอยู่
        raise ValueError(
            f"ไม่รู้จักโหมด {key!r} — ที่มีคือ {', '.join(ALL)}"
        )
    return MODES[normalized]


def menu_lines() -> list[str]:
    """ข้อความเมนูสำหรับถามผู้ใช้ — แยกจากการพิมพ์เพื่อให้เทสตรวจได้"""
    lines = ["", "  เลือกโหมดการทำงาน"]
    for i, key in enumerate(ORDER, start=1):
        mode = MODES[key]
        star = " (ค่าเริ่มต้น)" if key == DEFAULT else ""
        lines.append(f"    {i}) {mode.label:<10}{star}")
        lines.append(f"       {mode.summary}")
    # โหมดที่ไม่อยู่ในเมนูยังพิมพ์ชื่อเรียกได้ — ต้องบอกไว้ ไม่งั้นมันหายไปเงียบ ๆ
    # และคนที่เคยใช้อยู่จะคิดว่าถูกถอดออกแล้ว
    hidden = [k for k in ALL if k not in ORDER]
    if hidden:
        lines.append(f"       (พิมพ์ {' หรือ '.join(hidden)} เพื่อใช้โหมดที่ไม่อยู่ในลิสต์)")
    lines.append("")
    return lines


def parse_choice(raw: str) -> Mode | None:
    """
    ตีความสิ่งที่ผู้ใช้พิมพ์ — รับได้ทั้งเลขข้อและชื่อโหมด
    คืน None เมื่อพิมพ์อะไรที่ตีความไม่ได้ (ผู้เรียกควรถามซ้ำ ไม่ใช่เดา)
    """
    text = raw.strip().lower()
    if not text:
        return MODES[DEFAULT]        # กด Enter เฉย ๆ = เอาค่าเริ่มต้น
    if text.isdigit():
        index = int(text) - 1
        return MODES[ORDER[index]] if 0 <= index < len(ORDER) else None
    # เทียบกับ MODES ไม่ใช่ ORDER — พิมพ์ "room" ที่หน้าเมนูยังใช้ได้ทั้งที่ไม่มีข้อให้กด
    return MODES.get(text)
